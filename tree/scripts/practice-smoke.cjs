// Focused guided-practice checks. No students, saved answers, result fields or remote services.
const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const root = process.env.SMOKE_URL || 'http://127.0.0.1:4173';
const practiceCount = require('../src/data/practice.json').length;
const KEY = 'chemistree-self-assessment-v1';
const polarity = 'ib-2025-structure-2.2.6';
const atom = 'ib-2025-structure-1.2.1';
const uncurated = 'ib-2025-structure-3.2.12';
(async () => {
  const browser = await chromium.launch({executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage']});
  const context = await browser.newContext({viewport: {width: 1440, height: 1100}, acceptDownloads: true});
  const requests = [], errors = [];
  context.on('request', r => {if (r.url().startsWith('http')) requests.push({origin: new URL(r.url()).origin, path: new URL(r.url()).pathname, method: r.method()});});
  context.on('page', p => {p.setDefaultTimeout(8000); p.on('pageerror', e => errors.push(e.message));});
  try {
    const page = await context.newPage();
    await page.goto(`${root}#node=${polarity}`);
    await page.getByRole('heading', {name: 'Guided practice', exact: true}).waitFor();
    const read = () => page.evaluate(key => localStorage.getItem(key), KEY);
    const reflection = page.getByLabel('How do you feel about this statement?', {exact: true});
    assert.equal(await read(), null);
    const promptBefore = await page.getByLabel('AI instruction', {exact: true}).inputValue();
    const hint = page.getByRole('button', {name: 'Show a hint', exact: true});
    await hint.focus(); await page.keyboard.press('Enter');
    assert.equal(await page.locator('.practice-hints li').count(), 1);
    await page.getByRole('button', {name: 'Show next hint', exact: true}).click();
    assert.equal(await page.locator('.practice-hints li').count(), 2);
    assert.equal(await page.getByRole('button', {name: 'All hints shown', exact: true}).isDisabled(), true);
    await page.getByText('Show worked explanation', {exact: true}).focus(); await page.keyboard.press('Enter');
    assert.equal(await page.locator('.practice-solution').getAttribute('open'), '');
    await page.getByText('Show another explanation', {exact: true}).click();
    assert.equal(await page.locator('.practice-transfer details').getAttribute('open'), '');
    assert.equal(await read(), null, 'Hint and explanation reveals must not save progress');
    await page.getByRole('button', {name: 'Reflect on this statement', exact: true}).click();
    assert.equal(await reflection.evaluate(el => el === document.activeElement), true);
    assert.equal(await reflection.inputValue(), 'not-reviewed');
    assert.equal(await page.getByLabel('AI instruction', {exact: true}).inputValue(), promptBefore);
    const pending = page.waitForEvent('download');
    await page.getByRole('button', {name: 'Export self-assessment', exact: true}).click();
    const file = await pending;
    assert.equal(file.suggestedFilename(), 'chemistree-self-assessment.json');
    assert.deepEqual(JSON.parse(fs.readFileSync(await file.path(), 'utf8')), {schemaVersion: '1.0', mapVersion: '2.0', selfAssessments: {}});
    await reflection.selectOption('developing');
    const saved = await read();
    await page.evaluate(id => {location.hash = `node=${id}`;}, atom);
    await page.getByRole('button', {name: 'Show a hint', exact: true}).waitFor();
    assert.equal(await page.locator('.practice-solution').getAttribute('open'), null);
    await page.evaluate(id => {location.hash = `node=${id}`;}, polarity);
    await page.getByRole('button', {name: 'Show a hint', exact: true}).waitFor();
    assert.equal(await page.locator('.practice-hints li').count(), 0);
    assert.equal(await page.locator('.practice-solution').getAttribute('open'), null);
    assert.equal(await read(), saved);
    const guidedFilter = page.getByRole('checkbox', {name: `Guided exercises (${practiceCount})`, exact: true});
    await guidedFilter.check();
    assert.equal(await page.locator('.skill-card').count(), practiceCount);
    await page.getByRole('button', {name: 'List', exact: true}).click();
    assert.equal(await page.locator('.list-view button').count(), practiceCount);
    await page.getByLabel('Level filter', {exact: true}).selectOption('HL-only');
    assert.equal(await page.locator('.list-view button').count(), 0);
    await page.getByRole('status').filter({hasText: 'No matching statements.'}).waitFor();
    await page.evaluate(id => {location.hash = `node=${id}`;}, uncurated);
    await page.getByText('A guided exercise is not available for this statement yet.', {exact: false}).waitFor();
    assert.equal(await guidedFilter.isChecked(), false);
    assert.equal(await page.getByLabel('Level filter', {exact: true}).inputValue(), 'all');
    assert.equal(await page.locator('.list-view button.chosen').count(), 1);
    assert.equal(await page.locator('.guided-practice').count(), 0);
    assert.equal(await read(), saved);
    await page.evaluate(id => {location.hash = `node=${id}`;}, polarity);
    await page.getByRole('heading', {name: 'Guided practice', exact: true}).waitFor();
    await page.getByRole('button', {name: 'Map', exact: true}).click();
    await page.getByRole('button', {name: 'Show a hint', exact: true}).click();
    await page.getByText('Show worked explanation', {exact: true}).click();
    await page.locator('.guided-practice').scrollIntoViewIfNeeded();
    fs.mkdirSync('artifacts', {recursive: true});
    await page.locator('.guided-practice').evaluate(el => {const panel = document.getElementById('node-details'); panel.scrollTop += el.getBoundingClientRect().top - panel.getBoundingClientRect().top - 16;});
    await page.screenshot({path: 'artifacts/guided-practice-desktop.png', fullPage: true});
    await page.reload(); await page.getByRole('heading', {name: 'Guided practice', exact: true}).waitFor();
    assert.equal(await page.locator('.practice-hints li').count(), 0);
    assert.equal(await page.locator('.practice-solution').getAttribute('open'), null);
    assert.equal(await read(), saved);
    await page.setViewportSize({width: 390, height: 844});
    await page.getByRole('button', {name: 'Show a hint', exact: true}).click();
    await page.getByText('Show worked explanation', {exact: true}).click();
    await page.locator('.guided-practice').scrollIntoViewIfNeeded();
    await page.screenshot({path: 'artifacts/guided-practice-mobile.png', fullPage: true});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.getByRole('button', {name: 'Reflect on this statement', exact: true}).click();
    assert.equal(await reflection.evaluate(el => el === document.activeElement), true);
    assert.equal(await reflection.inputValue(), 'developing');
    assert.equal(await read(), saved);
    assert.deepEqual(errors, []);
    assert.ok(requests.every(r => r.origin === new URL(root).origin && r.method === 'GET'));
    console.log('Guided practice passed: hints, worked/transfer explanations, keyboard, filter/deep-link fallback, ephemeral state, unchanged exports/prompts/progress and mobile layout. Zero external requests.');
  } finally {await browser.close();}
})().catch(e => {console.error(e); process.exitCode = 1;});
